package com.github.andygoossens.gradle.plugins

import org.gradle.api.file.FileCollection
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.provider.SetProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional

abstract class ModernizerPluginExtension {

    /**
     * The version of modernizer-maven-plugin to be used.
     */
    @Input
    abstract Property<String> getToolVersion()

    /**
     * Enables violations based on target Java version, e.g., 1.8. For example,
     * Modernizer will detect uses of Vector as violations when targeting Java
     * 1.2 but not when targeting Java 1.1.
     */
    @Input
    abstract Property<String> getJavaVersion()

    /** Fail task if Modernizer detects any violations. */
    @Input
    abstract Property<Boolean> getFailOnViolations()

    /** Run Modernizer on test classes. */
    @Input
    abstract Property<Boolean> getIncludeTestClasses()

    /**
     * User-specified violation file. Also disables standard violation checks.
     * Can point to files from classpath using an absolute path, e.g.:
     *
     * classpath:/modernizer.xml
     *
     * for the default violations file.
     */
    @Input
    abstract Property<String> getViolationsFile()

    /**
     * User-specified violation files. The violations loaded from
     * violationsFiles override the ones specified in violationsFile (or the
     * default violations file if no violationsFile is given). Violations from
     * the latter files override violations from the former files.
     *
     * Can point to files from classpath using an absolute path, e.g.:
     *
     * classpath:/modernizer.xml
     *
     * for the default violations file.
     */
    @Input
    abstract ListProperty<String> getViolationsFiles()

    /**
     * Disables user-specified violations. This is a text file with one
     * exclusion per line in the javap format:
     *
     * java/lang/String.getBytes:(Ljava/lang/String;)[B.
     */
    @Input
    @Optional
    abstract Property<String> getExclusionsFile()

    /**
     * Log level to emit violations at, e.g., error, warn, info, debug, trace.
     */
    @Input
    abstract Property<String> getViolationLogLevel()

    /**
     * Classes annotated with {@code @Generated} will be excluded from
     * scanning, as will individual methods and constructors annotated with
     * {@code @Generated}, e.g., members generated by Lombok.
     */
    @Input
    abstract Property<Boolean> getIgnoreGeneratedClasses()

    /**
     * Violations to disable. Each exclusion should be in the javap format:
     *
     * java/lang/String.getBytes:(Ljava/lang/String;)[B.
     */
    @Input
    abstract SetProperty<String> getExclusions()

    /**
     * Violation patterns to disable. Each exclusion should be a
     * regular expression that matches the javap format:
     *
     * java/lang/.*
     */
    @Input
    abstract SetProperty<String> getExclusionPatterns()

    /**
     * Package prefixes to ignore, specified using &lt;ignorePackage&gt; child
     * elements. Specifying foo.bar subsequently ignores foo.bar.*,
     * foo.bar.baz.* and so on.
     */
    @Input
    abstract SetProperty<String> getIgnorePackages()
    
    /**
     * Full qualified class names (incl. package) to ignore, specified using
     * &lt;ignoreClassNamePattern&gt; child elements. Each exclusion should be
     * a regular expression that matches a package and/or class; the package
     * will be / not . separated (ASM's format).
     */
    @Input
    abstract SetProperty<String> getIgnoreClassNamePatterns()

    /**
     * Skips the plugin execution.
     */
    @Input
    abstract Property<Boolean> getSkip()

    FileCollection mainSourceDirectories
    FileCollection mainOutputDirectories
    FileCollection testSourceDirectories
    FileCollection testOutputDirectories
    
    ModernizerPluginExtension(FileCollection mainSourceDirectories,
                              FileCollection mainOutputDirectories, FileCollection testSourceDirectories,
                              FileCollection testOutputDirectories, String toolVersion) {
        this.mainSourceDirectories = mainSourceDirectories
        this.mainOutputDirectories = mainOutputDirectories
        this.testSourceDirectories = testSourceDirectories
        this.testOutputDirectories = testOutputDirectories

        this.getToolVersion().convention(toolVersion)
        this.getFailOnViolations().convention(false)
        this.getIncludeTestClasses().convention(false)
        this.getViolationsFile().convention("classpath:/modernizer.xml")
        this.getViolationLogLevel().convention("warn")
        this.getIgnoreGeneratedClasses().convention(true)
        this.getSkip().convention(false)
    }
}
